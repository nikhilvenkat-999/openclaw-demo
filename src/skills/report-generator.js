/**
 * Report Generator Skill
 */
export const reportGenerator = {
  name: 'report-generator',
  description: 'Generate automated reports from aggregated data',

  /**
   * Initialize the skill
   */
  async init() {
    console.log('   Report generator initialized');
  },

  /**
   * Execute the skill
   */
  async execute(query) {
    const lowerQuery = query.toLowerCase();

    // Determine report type
    if (lowerQuery.includes('daily') || lowerQuery.includes('full') || lowerQuery.includes('detailed')) {
      return generateDailyReport();
    }

    if (lowerQuery.includes('sales') || lowerQuery.includes('revenue')) {
      return generateSalesReport();
    }

    // Default to summary
    return generateSummaryReport();
  }
};
